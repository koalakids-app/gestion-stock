async function ctEnvoyerOtp(){
  const empId=(document.getElementById('ff_salarie_employe_id')||{}).value||'';
  if(!empId)return toast('Choisissez d’abord la fiche du/de la salarié(e).');
  if(!fillRep||!fillRep.id)await saveFill(true);
  if(!fillRep||!fillRep.id)return toast('Enregistrez d’abord le contrat avant d’envoyer un code.');
  const r=await callFn('signature-otp',{action:'envoyer',reponse_id:fillRep.id,employe_id:empId,canal:'email'});
  if(!r.ok||!r.data||r.data.erreur){toast('Erreur : '+((r.data&&r.data.erreur)||'envoi impossible'));return;}
  CT_OTP_SENT_AT=new Date().toISOString();
  toast('Code envoyé par e-mail.');
  ctRenderOtp();
}
async function ctVerifierOtp(){
  if(!fillRep||!fillRep.id)return toast('Enregistrez d’abord le contrat.');
  const code=(document.getElementById('ff_ct_otp_saisie')||{}).value||'';
  if(!/^[0-9]{6}$/.test(code))return toast('Saisissez le code à 6 chiffres reçu par e-mail.');
  const r=await callFn('signature-otp',{action:'verifier',reponse_id:fillRep.id,code});
  if(!r.ok||!r.data||!r.data.ok){toast('Code incorrect ou expiré.'+((r.data&&r.data.erreur)?(' '+r.data.erreur):''));return;}
  CT_OTP_VERIFIED=true;CT_OTP_VERIFIED_AT=r.data.verified_at||new Date().toISOString();
  toast('Identité vérifiée.');
  ctRenderOtp();
}

