/* ---------- EXPORT « CERFA OFFICIEL » ----------
   Le PDF vierge téléchargé sur service-public.gouv.fr sert de fond : on ne
   redessine rien, on tamponne les réponses aux coordonnées réelles du
   formulaire (croix dans les cases, texte dans les zones de saisie roses).
   Le document sorti est donc le cerfa lui-même, rempli.

   Le fichier vierge doit être déposé dans le bucket Supabase « assets » au
   chemin C17_PDF_PATH. S’il est absent ou illisible, l’export bascule
   automatiquement sur le rendu de secours (pdfDessine).

   Coordonnées : origine en haut à gauche, en points (comme pdftotext).
   pdf-lib place l’origine en bas à gauche : y_pdf = hauteurPage - y. */
const C17_PDF_PATH='documents/cerfa_17580.pdf';
function c17PdfUrl(){
  try{return sb.storage.from('assets').getPublicUrl(C17_PDF_PATH).data.publicUrl;}catch(e){return null;}
}
/* Les polices standard PDF sont encodées en WinAnsi : on remplace ce qu’elles
   ne savent pas rendre plutôt que de laisser pdf-lib lever une exception. */
function c17Ansi(v){
  return String(v==null?'':v)
    .replace(/[\u2018\u201A\u201B]/g,'\u2019').replace(/[\u201C\u201D]/g,'"')
    .replace(/[\u2013\u2014]/g,'-').replace(/\u2265/g,'>=').replace(/\u2264/g,'<=')
    .replace(/[\u00A0\u202F]/g,' ').replace(/\u2044/g,'/').replace(/[\u2022\u00B7]/g,'-')
    .replace(/[^\u0020-\u00FF\u20AC\u2019]/g,' ');
}
function c17Wrap(txt,font,size,maxW){
  const out=[];
  String(txt).split(/\r?\n/).forEach(par=>{
    let cur='';
    par.split(/\s+/).forEach(w=>{
      const t=cur?cur+' '+w:w;
      if(cur&&font.widthOfTextAtSize(t,size)>maxW){out.push(cur);cur=w;}else cur=t;
    });
    out.push(cur);
  });
  return out;
}
